// EXPERIMENT 1
public class IdentifierAndVariable {
    public static void main(String[] args) {

        // Declaring and assigning variables
        String studentName = "Kartik";
        int rollNumber = 017;
        int subject1Marks = 85;
        int subject2Marks = 90;
        int subject3Marks = 88;

        // Printing student details
        System.out.println("Student Name: " + studentName);
        System.out.println("Roll Number: " + rollNumber);
        System.out.println("Subject 1 Marks: " + subject1Marks);
        System.out.println("Subject 2 Marks: " + subject2Marks);
        System.out.println("Subject 3 Marks: " + subject3Marks);
    }
}